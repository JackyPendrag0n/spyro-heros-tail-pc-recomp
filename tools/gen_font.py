"""Render ASCII 32..126 of DejaVu Sans Mono Bold into a C alpha atlas (loader/gfx/font.h).
DejaVu fonts: Bitstream Vera license (free redistribution, including embedding)."""
from PIL import Image, ImageDraw, ImageFont
CW, CH, SIZE = 12, 22, 18
f = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf', SIZE)
cols, n = 16, 95
rows = (n + cols - 1) // cols
img = Image.new('L', (cols * CW, rows * CH), 0)
d = ImageDraw.Draw(img)
asc, desc = f.getmetrics()
for i in range(n):
    c = chr(32 + i)
    x, y = (i % cols) * CW, (i // cols) * CH
    d.text((x + 1, y + (CH - asc - desc) // 2), c, font=f, fill=255)
data = img.tobytes()
with open('loader/gfx/font.h', 'w') as o:
    o.write('/* generated by tools/gen_font.py from DejaVu Sans Mono Bold (Bitstream Vera license) */\n')
    o.write(f'#define FONT_CW {CW}\n#define FONT_CH {CH}\n#define FONT_COLS {cols}\n#define FONT_ROWS {rows}\n')
    o.write(f'static const unsigned char font_atlas[{len(data)}] = {{\n')
    for i in range(0, len(data), 32):
        o.write(','.join(str(b) for b in data[i:i+32]) + ',\n')
    o.write('};\n')
img.save('font.png')
