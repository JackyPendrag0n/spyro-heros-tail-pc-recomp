#!/usr/bin/env python3
"""Generate loader/gen_kernel.c from data/kernel_imports.json.

Every imported kernel function gets a *weak* fallback k_<Name> with the exact
calling convention and argument count, which logs the call and returns 0.
A strong definition anywhere else in the loader overrides it.  Variables are
expected to be defined (strongly) as kv_<Name> in kvars.c.
"""
import json, sys

imps = json.load(open(sys.argv[1]))
out = ['/* generated by tools/gen_kstubs.py - do not edit */',
       '#include "xbox.h"', '']
table = []
seen = set()
for e in sorted(imps, key=lambda e: e['ordinal']):
    n, name, conv = e['ordinal'], e['name'], e.get('conv')
    if name in seen:
        continue
    seen.add(name)
    if conv == 'VAR':
        out.append(f'extern char kv_{name}[];')
        table.append((n, f'kv_{name}', name))
        continue
    nargs = e['nargs']
    # 64-bit by-value params occupy two stack slots under stdcall
    params_decl = []
    for p in e.get('params', [])[:nargs]:
        t = p.replace('IN ', '').replace('OUT ', '').replace('OPTIONAL', '').strip()
        if t.split()[0] in ('LARGE_INTEGER', 'ULARGE_INTEGER', 'LONGLONG', 'ULONGLONG') and '*' not in t:
            params_decl += [p + '_lo', p + '_hi']
        else:
            params_decl.append(p)
    e['params'] = params_decl
    nargs = len(params_decl)
    if conv == 'FASTCALL':
        cc = 'FASTCALL'
    elif conv in ('_cdecl', 'CDECL'):
        cc = 'CDECLX'
    else:
        cc = 'STDCALL'
    if conv in ('_cdecl', 'CDECL'):
        params = 'const char *fmt, ...'
        logargs = '"%s", fmt'
        fmt = 'fmt=%s'
    else:
        params = ', '.join(f'u32 a{i}' for i in range(nargs)) or 'void'
        fmt = ' '.join(f'{p.split()[-1] if p.split() else "a"}=%08x' for p in e.get('params', [])[:nargs])
        logargs = ', '.join(f'a{i}' for i in range(nargs))
    out.append(f'__attribute__((weak)) u32 {cc} k_{name}({params})')
    out.append('{')
    if logargs:
        out.append(f'    kstub_log({n}, "{name}", "{fmt}", {logargs});')
    else:
        out.append(f'    kstub_log({n}, "{name}", "");')
    out.append('    return 0;')
    out.append('}')
    out.append('')
    table.append((n, f'k_{name}', name))

out.append('const struct kexport kernel_exports[] = {')
for n, sym, name in table:
    out.append(f'    {{ {n}, (void *)&{sym}, "{name}" }},')
out.append('    { 0, 0, 0 }')
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(f'{len(table)} exports -> {sys.argv[2]}')
